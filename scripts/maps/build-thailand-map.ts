// scripts/maps/build-thailand-map.ts
// Turns the geoBoundaries THA ADM1 GeoJSON (Royal Thai Survey Department via
// HDX, CC BY 3.0 IGO) into pre-projected SVG paths, so the admin map needs no
// mapping library at runtime.
//
// Usage: tsx scripts/maps/build-thailand-map.ts <geoBoundaries-THA-ADM1_simplified.geojson>
// Source: https://www.geoboundaries.org/api/current/gbHumanitarian/THA/ADM1/

import fs from 'node:fs';
import path from 'node:path';
import { PROVINCES } from '@/lib/onboarding/provinces';

type Ring = number[][];
type Feature = { properties: { shapeName: string }; geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: Ring[] | Ring[][] } };

const WIDTH = 600;
const TOLERANCE = 0.35; // px, Douglas–Peucker
const MIN_RING_AREA = 0.6; // px², drops specks of islands

const input = process.argv[2];
if (!input) throw new Error('Pass the GeoJSON file path');
const features: Feature[] = JSON.parse(fs.readFileSync(input, 'utf8')).features;

const key = (name: string) => name.toLowerCase().replace(/[^a-z]/g, '');
const codeByName = new Map(PROVINCES.map(p => [key(p.en), p.code]));

// Web Mercator, fitted to the country's bounds.
const merc = ([lon, lat]: number[]) => [lon, Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360)) * (180 / Math.PI)];
const polygons = (f: Feature) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates as Ring[]] : (f.geometry.coordinates as Ring[][]));
const all = features.flatMap(f => polygons(f).flatMap(p => p.flatMap(r => r.map(merc))));
const extent = (i: 0 | 1) => all.reduce(([lo, hi], p) => [Math.min(lo, p[i]), Math.max(hi, p[i])], [Infinity, -Infinity]);
const [[minX, maxX], [minY, maxY]] = [extent(0), extent(1)];
const scale = WIDTH / (maxX - minX);
const HEIGHT = Math.ceil((maxY - minY) * scale);
const project = (pt: number[]) => { const [x, y] = merc(pt); return [(x - minX) * scale, (maxY - y) * scale]; };

function simplify(points: number[][]): number[][] {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points[points.length - 1]];
  let index = 0, max = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const d = dx === 0 && dy === 0 ? Math.hypot(x - a[0], y - a[1]) : Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / Math.hypot(dx, dy);
    if (d > max) { max = d; index = i; }
  }
  if (max <= TOLERANCE) return [a, b];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}
const area = (r: number[][]) => Math.abs(r.reduce((s, [x, y], i) => { const [nx, ny] = r[(i + 1) % r.length]; return s + x * ny - nx * y; }, 0) / 2);
const r1 = (n: number) => Math.round(n * 10) / 10;

const out: Record<string, { d: string; box: [number, number, number, number] }> = {};
for (const feature of features) {
  const code = codeByName.get(key(feature.properties.shapeName));
  if (!code) throw new Error(`Unmatched province: ${feature.properties.shapeName}`);
  const rings = polygons(feature).flatMap(p => p.map(r => simplify(r.map(project))).filter(r => r.length >= 4 && area(r) >= MIN_RING_AREA));
  const xs = rings.flat().map(p => p[0]), ys = rings.flat().map(p => p[1]);
  out[code] = {
    d: rings.map(r => `M${r.slice(0, -1).map(([x, y]) => `${r1(x)} ${r1(y)}`).join('L')}Z`).join(''),
    box: [r1(Math.min(...xs)), r1(Math.min(...ys)), r1(Math.max(...xs) - Math.min(...xs)), r1(Math.max(...ys) - Math.min(...ys))],
  };
}
const missing = PROVINCES.filter(p => !out[p.code]);
if (missing.length) throw new Error(`Missing provinces: ${missing.map(p => p.en).join(', ')}`);

const body = `// Generated by scripts/maps/build-thailand-map.ts — do not edit by hand.
// Boundaries: Royal Thai Survey Department via HDX / geoBoundaries, CC BY 3.0 IGO.
// Paths are Web Mercator, ${WIDTH}×${HEIGHT}; box is [x, y, width, height].

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export const MAP_ATTRIBUTION = 'Boundaries: Royal Thai Survey Department via HDX / geoBoundaries (CC BY 3.0 IGO)';
export const PROVINCE_SHAPES: Record<string, { d: string; box: [number, number, number, number] }> = ${JSON.stringify(out)};
`;
const target = path.join(process.cwd(), 'lib/maps/thailand-provinces.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, body);
console.log(`Wrote ${target} (${(body.length / 1024).toFixed(0)} KB, ${WIDTH}×${HEIGHT})`);
